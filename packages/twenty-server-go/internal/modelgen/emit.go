func sdl(objects []*object) ([]byte, error) {
	byID := make(map[string]*object, len(objects))
	for _, o := range objects {
		byID[o.id] = o
	}

	var b strings.Builder
	b.WriteString(sdlPrelude)
	for _, o := range objects {
		typeName := capitalize(o.NameSingular)
		fmt.Fprintf(&b, "\ntype %s {\n", typeName)
		for _, f := range o.fields {
			lines, err := sdlFields(o, f, byID)
			if err != nil {
				return nil, err
			}
			for _, line := range lines {
				fmt.Fprintf(&b, "  %s\n", line)
			}
		}
		b.WriteString("}\n")
		fmt.Fprintf(&b, "\ntype %sEdge {\n  node: %s!\n  cursor: Cursor!\n}\n", typeName, typeName)
		fmt.Fprintf(&b, "\ntype %sConnection {\n  totalCount: Int\n  edges: [%sEdge!]!\n  pageInfo: PageInfo!\n}\n", typeName, typeName)
		for _, f := range o.fields {
			if f.Type != model.TypeSelect && f.Type != model.TypeMultiSelect {
				continue
			}
			fmt.Fprintf(&b, "\nenum %s {\n", enumName(o, f))
			for _, option := range f.Options {
				fmt.Fprintf(&b, "  %s\n", option)
			}
			b.WriteString("}\n")
		}
	}
	return []byte(b.String()), nil
}

func enumName(o *object, f field) string {
	return capitalize(o.NameSingular) + capitalize(f.Name) + "Enum"
}

func sdlFields(o *object, f field, byID map[string]*object) ([]string, error) {
	notNull := f.nullable != nil && !*f.nullable
	bang := ""
	if notNull {
		bang = "!"
	}

	switch f.Type {
	case model.TypeRelation, model.TypeMorph:
		target, ok := byID[f.target]
		if !ok {
			return nil, fmt.Errorf("field %s.%s targets an unknown object", o.NameSingular, f.Name)
		}
		if f.settings.RelationType == "ONE_TO_MANY" {
			return []string{fmt.Sprintf("%s: %sConnection", f.Name, capitalize(target.NameSingular))}, nil
		}
		return []string{
			fmt.Sprintf("%s: ID%s", f.settings.JoinColumnName, bang),
			fmt.Sprintf("%s: %s", f.Name, capitalize(target.NameSingular)),
		}, nil
	case model.TypeMultiSelect:
		element := enumName(o, f)
		if f.nullable == nil || !*f.nullable {
			element += "!"
		}
		return []string{fmt.Sprintf("%s: [%s]%s", f.Name, element, bang)}, nil
	case model.TypeSelect:
		return []string{fmt.Sprintf("%s: %s%s", f.Name, enumName(o, f), bang)}, nil
	case model.TypeFullName, model.TypeEmails, model.TypePhones, model.TypeLinks,
		model.TypeCurrency, model.TypeAddress, model.TypeActor, model.TypeRichText:
		return []string{fmt.Sprintf("%s: %s%s", f.Name, pascalSnake(string(f.Type)), bang)}, nil
	}

	scalar, ok := scalarTypes[f.Type]
	switch {
	case f.Type == model.TypeNumber:
		scalar = numberScalar(f.settings.DataType)
	case !ok:
		return nil, fmt.Errorf("field %s.%s has no GraphQL type for %s", o.NameSingular, f.Name, f.Type)
	}
	return []string{fmt.Sprintf("%s: %s%s", f.Name, scalar, bang)}, nil
}

func numberScalar(dataType string) string {
	switch dataType {
	case "int":
		return "Int"
	case "bigint":
		return "BigInt"
	default:
		return "Float"
	}
}

