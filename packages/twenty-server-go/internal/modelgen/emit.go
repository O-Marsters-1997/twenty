func goSource(objects []*object) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/modelgen. DO NOT EDIT.\n\npackage model\n\nvar Objects = []Object{\n")
	for _, o := range objects {
		fmt.Fprintf(&b, "{NameSingular: %q, NamePlural: %q, Table: %q, Fields: []Field{\n", o.NameSingular, o.NamePlural, o.Table)
		for _, f := range o.Fields {
			fmt.Fprintf(&b, "{Name: %q, Type: %s", f.Name, constName(f.Type))
			if len(f.Columns) > 0 {
				b.WriteString(", Columns: []Column{")
				for _, c := range f.Columns {
					fmt.Fprintf(&b, "{Name: %q, SubField: %q}, ", c.Name, c.SubField)
				}
				b.WriteString("}")
			}
			if len(f.Options) > 0 {
				b.WriteString(", Options: []string{")
				for _, option := range f.Options {
					fmt.Fprintf(&b, "%q, ", option)
				}
				b.WriteString("}")
			}
			b.WriteString("},\n")
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format model: %w", err)
	}
	return src, nil
}

